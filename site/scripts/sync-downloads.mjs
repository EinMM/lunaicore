// Generates src/components/DownloadsEn.astro and DownloadsAr.astro from the landing pages, so the
// Downloads pages reuse the landing wording instead of repeating it by hand.
//   node scripts/sync-downloads.mjs           writes the two components
//   node scripts/sync-downloads.mjs --check   exits 1 if they are out of date (landing text changed)
// Only the language of each page is kept (data-en / data-ar attributes are dropped); asset paths become absolute.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const die = (message) => {
  console.error(`sync-downloads: ${message}`);
  process.exit(1);
};
const between = (text, start, end, from = 0) => {
  const i = text.indexOf(start, from);
  if (i < 0) die(`marker not found: ${start.slice(0, 60)}`);
  const j = text.indexOf(end, i + start.length);
  if (j < 0) die(`end marker not found: ${end.slice(0, 60)}`);
  return text.slice(i + start.length, j);
};
// data-en / data-ar / data-aria-* / data-href-*: quoted values or {`template`} values
const DATA_ATTR = /\s+data-(?:aria-|href-)?(?:en|ar)=(?:"[^"]*"|\{`[^`]*`\})/g;
const clean = (html) =>
  html.replace(DATA_ATTR, "").replace(/(src=")(?:\.\.\/)?assets\//g, "$1/assets/");
const dedent = (text, spaces) => text.split("\n").map((l) => l.replace(new RegExp(`^ {0,${spaces}}`), "")).join("\n");

const FAQ = {
  en: ["Does Luna work on Windows 10?", "Why does Windows show a SmartScreen warning?", "How can I verify the installer?"],
  ar: ["هل تعمل لونا على Windows 10؟", "لماذا يظهر تحذير SmartScreen؟", "كيف أتحقق من ملف التثبيت؟"],
};

function build(lang) {
  const file = path.join(site, "src/pages", lang === "ar" ? "ar/index.astro" : "index.astro");
  const src = fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");

  const requirements = between(src, '<section id="requirements" class="section-texture">\n      <div class="container">\n', "\n      </div>\n    </section>");

  const heroMetaStart = src.indexOf('<div class="hero-meta">');
  if (heroMetaStart < 0) die("hero-meta not found");
  const heroMeta = between(src, "`}>", "</span>", src.indexOf("<span data-en={", heroMetaStart)).trim();

  const cta = src.slice(src.indexOf('<section id="get" class="cta">'));
  const buttonLabel = between(cta, 'data-ar="', "</span>", cta.indexOf('<span data-en="Download Luna for Windows"')).split(">").pop().trim();
  const notesLabel = between(cta, "<a href={release.releaseUrl}", "</a>").split(">").pop().trim();

  const faqSection = src.slice(src.indexOf('<section id="faq"'));
  const cards = FAQ[lang].map((title) => {
    const at = faqSection.indexOf(`>${title}</h3>`);
    if (at < 0) die(`FAQ item not found: ${title}`);
    const start = faqSection.lastIndexOf('<article class="feature-card">', at);
    const end = faqSection.indexOf("</article>", at) + "</article>".length;
    return clean(faqSection.slice(start, end));
  });

  const body = `---
// GENERATED by scripts/sync-downloads.mjs from src/pages/${lang === "ar" ? "ar/" : ""}index.astro. Do not edit by hand:
// change the landing page, then run \`npm run sync:downloads\`.
import { release, formatDate } from "../data/release";
---
<div class="container page-block">
  <h1>${buttonLabel}</h1>
  <p class="page-meta">${heroMeta} · <time datetime={release.releaseDate}>{formatDate(release.releaseDate, "${lang}")}</time></p>
  <div class="page-actions">
    <a class="button" href={release.downloadUrl}>
      <img class="button-icon" src="/assets/icons/download.svg" alt="" aria-hidden="true">
      <span>${buttonLabel}</span>
    </a>
    <a class="page-link" href={release.releaseUrl}>${notesLabel}</a>
  </div>
</div>

<div class="container narrow prose page-block">
  <slot name="install" />
</div>

<section id="requirements" class="page-block">
  <div class="container">
${dedent(clean(requirements), 4)}
  </div>
</section>

<section id="faq" class="page-block">
  <div class="container">
    <div class="feature-grid">
${cards.map((c) => dedent(c, 6)).join("\n")}
    </div>
  </div>
</section>
`;
  return { name: lang === "ar" ? "DownloadsAr.astro" : "DownloadsEn.astro", body, title: buttonLabel };
}

let stale = 0;
for (const lang of ["en", "ar"]) {
  const { name, body } = build(lang);
  const target = path.join(site, "src/components", name);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
  if (check) {
    if (current !== body) { console.error(`sync-downloads: ${name} is out of date`); stale++; }
  } else {
    fs.writeFileSync(target, body, "utf8");
    console.log(`sync-downloads: wrote src/components/${name} (${body.length} bytes)`);
  }
}
if (check) {
  if (stale) process.exit(1);
  console.log("sync-downloads: up to date");
}
